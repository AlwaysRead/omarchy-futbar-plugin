const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const h = vm.createContext({Date, console});
vm.runInContext(fs.readFileSync('qml/data/FutPlayerHistory.js','utf8').replace(/^\.pragma library\s*/,''),h);
const data = JSON.parse(fs.readFileSync('tests/fixtures/player-gamelog.json','utf8'));
const parsed = h.parse(data);
assert.equal(parsed.matches.length,3);
assert(parsed.competitions.length > 0);
assert(parsed.matches.every(m => m.goals !== '—'));
assert(parsed.matches[0].timestamp >= parsed.matches[1].timestamp);
const first = data.seasonTypes.flatMap(s=>s.categories).find(c=>c.events.length);
first.events.push(first.events[0]);
assert.equal(h.parse(data).matches.length,3);
assert.equal(h.parse({}).matches.length,0);
assert.equal(h.requestUrl('$(touch /tmp/no)',2026,''),'');
assert.equal(h.requestUrl('123',2026,'eng.1&url=evil'),'');
assert.equal(h.requestUrl('123',1979,''),'');
assert(h.requestUrl('123',2025,'eng.1').endsWith('?season=2025&league=eng.1'));
data.names=[];
assert(h.parse(data).matches.every(m=>m.goals==='—' && m.rating==='—'));
console.log('PASS: recorded player history, named statistics, filters and bounded parsing');
